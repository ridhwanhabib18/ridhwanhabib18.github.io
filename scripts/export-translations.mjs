// Writes docs/translation-review.md: every English text next to its Indonesian translation, for a native speaker to review.
// Usage: npm run translations   (builds the server bundle first, so no full site build is needed)
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const build = spawnSync('npx', ['vite', 'build', '--ssr', 'src/entry-server.tsx', '--outDir', 'dist-server', '--logLevel', 'warn'], { stdio: 'inherit', shell: true });
if (build.status !== 0) process.exit(build.status ?? 1);

const { translationRows } = await import(pathToFileURL(join(process.cwd(), 'dist-server/entry-server.js')).href);
const rows = translationRows();

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const areas = [...new Set(rows.map((r) => r.area))];

let md = `# Translation review

English next to Indonesian for every text on the site (${rows.length} rows). Generated by \`npm run translations\`; edit the real texts in the source files, not this file.

How to review: read each Indonesian text as a native reader would. Mark anything that sounds stiff, is too literal, or changes the meaning. Rows marked "same" have identical English and Indonesian text; that is fine for names and technology terms, and worth a look for sentences.

`;

for (const area of areas) {
  const list = rows.filter((r) => r.area === area);
  md += `## ${area} (${list.length})\n\n| Where | English | Indonesian | Same |\n|---|---|---|---|\n`;
  for (const r of list) md += `| ${cell(r.where)} | ${cell(r.en)} | ${cell(r.id)} | ${r.same ? 'same' : ''} |\n`;
  md += '\n';
}

mkdirSync('docs', { recursive: true });
writeFileSync('docs/translation-review.md', md);
console.log(`translations: wrote docs/translation-review.md (${rows.length} rows, ${rows.filter((r) => r.same).length} identical)`);
